  function normalizeLang(code) {
    var c = String(code || "").toLowerCase().replace(/_/g, "-");
    if (c.indexOf("ko") === 0) return "ko";
    if (c.indexOf("ja") === 0) return "ja";
    if (c.indexOf("zh") === 0) return "zh";
    // China-related region tags sometimes appear without zh- prefix in rare cases
    if (c === "cn" || c === "tw" || c === "hk" || c === "mo") return "zh";
    return null;
  }

  function detectLang() {
    try {
      var saved = localStorage.getItem(LANG_KEY);
      if (saved && SUPPORTED.indexOf(saved) !== -1) return saved;
    } catch (e) {}

    var list = [];
    if (global.navigator) {
      if (global.navigator.languages && global.navigator.languages.length) {
        list = Array.prototype.slice.call(global.navigator.languages);
      } else if (global.navigator.language) {
        list = [global.navigator.language];
      }
    }

    for (var i = 0; i < list.length; i++) {
      var mapped = normalizeLang(list[i]);
      if (mapped) return mapped;
    }
    return "en";
  }

  var currentLang = detectLang();

  function t(key, params) {
    var dict = I18N[currentLang] || I18N.en;
    var text = dict[key];
    if (text == null) text = (I18N.en[key] != null ? I18N.en[key] : key);
    if (params) {
      Object.keys(params).forEach(function (name) {
        text = String(text).split("{" + name + "}").join(String(params[name]));
      });
    }
    return text;
  }

  function applyI18n() {
    var htmlLang = currentLang === "zh" ? "zh-CN" : currentLang;
    document.documentElement.lang = htmlLang;
    document.title = t("meta.title");

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      el.setAttribute("alt", t(el.getAttribute("data-i18n-alt")));
    });
    document.querySelectorAll("[data-i18n-value]").forEach(function (el) {
      el.setAttribute("value", t(el.getAttribute("data-i18n-value")));
    });

    var select = document.getElementById("langSelect");
    if (select) {
      select.value = currentLang;
      select.setAttribute("aria-label", t("lang.aria"));
    }

    if (typeof global.onI18nApplied === "function") {
      global.onI18nApplied(currentLang);
    }
  }

  function setLang(lang, persist) {
    if (SUPPORTED.indexOf(lang) === -1) lang = "en";
    currentLang = lang;
    if (persist !== false) {
      try {
        localStorage.setItem(LANG_KEY, lang);
      } catch (e) {}
    }
    applyI18n();
  }

  global.I18N = I18N;
  global.t = t;
  global.applyI18n = applyI18n;
  global.setLang = setLang;
  global.getLang = function () { return currentLang; };
  global.detectLang = detectLang;
